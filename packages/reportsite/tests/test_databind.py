import json

import pytest

from reportsite import SpecError, build_site, check_site, passed
from reportsite.databind import DATA_JS_PATH

DATA = {
    "metrics.json": [{"name": "alpha", "count": 3}, {"name": "beta", "count": 5}],
    "summary.json": {"total": 8, "totals": {"open": 2}},
    "rows.csv": [{"name": "gamma", "count": 7}, {"name": "delta, d", "count": 1}],
}
BODY = ('<div data-table="metrics.json"></div>'
        '<table data-table="rows.csv" data-columns="name,count"></table>'
        '<p>Total: <span data-value="summary.json#total"></span> '
        'open <span data-value="summary.json#totals.open"></span></p>')


def spec(body=BODY, data=DATA):
    return {"title": "Sample", "conclusion_html": "<p>ok</p>",
            "pages": [{"id": "data", "title": "Data", "body_html": body}], "data": data}


@pytest.fixture
def site(tmp_path):
    out = tmp_path / "site"
    build_site(spec(), str(out))
    return out


def rules(site):
    return {f.rule for f in check_site(str(site))}


def test_build_writes_data_script_and_links(site):
    for f in ["site_data/metrics.json", "site_data/summary.json", "site_data/rows.csv", DATA_JS_PATH]:
        assert (site / f).is_file()
    assert json.loads((site / "site_data/metrics.json").read_text())[0]["name"] == "alpha"
    assert (site / "site_data/rows.csv").read_text().splitlines()[0] == "name,count"
    js = (site / DATA_JS_PATH).read_text()
    assert "do not edit by hand" in js and "reportsite-data-binding" in js
    for page in ["index.html", "data.html"]:
        assert DATA_JS_PATH in (site / page).read_text()
    assert check_site(str(site)) == []
    assert passed(check_site(str(site)))


def test_site_without_data_unchanged(tmp_path):
    out = tmp_path / "s"
    build_site({"title": "T", "conclusion_html": "<p>c</p>"}, str(out))
    assert not (out / "site_data").exists() and not (out / DATA_JS_PATH).exists()
    assert check_site(str(out)) == []


def test_bad_spec_data_rejected_before_write(tmp_path):
    with pytest.raises(SpecError):
        build_site(spec(data={"../x.json": []}), str(tmp_path / "o"))
    with pytest.raises(SpecError):
        build_site(spec(data={"a.csv": {"not": "rows"}}), str(tmp_path / "o"))
    assert not (tmp_path / "o").exists()


def test_missing_file(site):
    p = site / "data.html"
    p.write_text(p.read_text().replace("metrics.json", "nope.json"))
    assert "data.missing_file" in rules(site)


def test_bad_ref_path(site):
    p = site / "data.html"
    p.write_text(p.read_text().replace("metrics.json", "../metrics.json"))
    assert "data.bad_ref" in rules(site)


def test_missing_field(site):
    p = site / "data.html"
    p.write_text(p.read_text().replace("#total", "#nothere"))
    assert "data.missing_field" in rules(site)


def test_missing_column(site):
    p = site / "data.html"
    p.write_text(p.read_text().replace("name,count", "name,zzz"))
    assert "data.missing_field" in rules(site)


def test_table_shape(site):
    p = site / "data.html"
    p.write_text(p.read_text().replace('data-table="metrics.json"', 'data-table="summary.json"'))
    assert "data.table_shape" in rules(site)


def test_malformed_json_and_csv(site):
    (site / "site_data/metrics.json").write_text("{not json")
    (site / "site_data/rows.csv").write_text("a,b\n1\n")
    r = rules(site)
    assert {"data.invalid_json", "data.invalid_csv"} <= r


def test_unreferenced_bad_data_file_still_caught(site):
    (site / "site_data/extra.json").write_text("[")
    assert "data.invalid_json" in rules(site)


def test_script_missing(site):
    (site / DATA_JS_PATH).unlink()
    assert "data.script_missing" in rules(site)


def test_script_unlinked(site):
    p = site / "data.html"
    p.write_text(p.read_text().replace(f'<script src="{DATA_JS_PATH}"></script>', ""))
    assert "data.script_unlinked" in rules(site)


def test_script_hand_edited(site):
    s = site / DATA_JS_PATH
    s.write_text(s.read_text().replace('var DIR = "site_data/"', 'var DIR = "site_data/x/"'))
    assert "data.script_modified" in rules(site)


def test_script_marker_removed(site):
    s = site / DATA_JS_PATH
    s.write_text(s.read_text().replace("/* generated by reportsite - do not edit by hand */", ""))
    assert "data.script_modified" in rules(site)


def test_secret_in_site_data_still_flagged(tmp_path):
    cred = "pass" + "word" + "=" + "hunter2hunter2"
    out = tmp_path / "s"
    build_site(spec(data={"metrics.json": [{"name": cred, "count": 1}]}, body='<div data-table="metrics.json"></div>'),
               str(out))
    assert "secret.leak" in rules(out)
