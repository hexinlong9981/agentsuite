"""Data separation: typed containers, the generated binding script, data files.

Container attribute contract (authors write these in page bodies)
-----------------------------------------------------------------
Table container -- renders a data file as a table::

    <div data-table="metrics.json"></div>
    <table data-table="metrics.csv" data-columns="name,count"></table>

* ``data-table="<file>"``: a file directly inside ``site_data/`` (letters, digits,
  ``.``, ``_``, ``-``; extension ``.json`` or ``.csv``). No path separators, no ``#``.
* JSON table data: a list of objects. CSV table data: a header row + rows.
* ``data-columns="a,b"`` (optional): the columns to show, in order. Default: every
  key (JSON: first-seen order across rows) or every CSV header.
* On a ``<table>`` the script fills its ``<thead>``/``<tbody>``; on any other element
  it inserts a ``<table>`` inside it.

Value container -- injects one field::

    <span data-value="summary.json#total"></span>
    <span data-value="summary.json#totals.open"></span>

* ``data-value="<file>#<field>"``. JSON: the top-level value must be an object;
  ``<field>`` is a dotted path of keys. CSV: ``<field>`` is a header name and the
  first data row supplies the value.

``site_data/`` is written from ``SiteSpec.data`` (``{filename: content}``): JSON files
hold any JSON-serialisable value, CSV files hold a list of row objects. The binding
script ``site_assets/rs-data.js`` is GENERATED and never hand-edited; it carries a
marker and a content hash that ``check_site`` verifies (``data.script_modified``).
Values are inserted with ``textContent`` (never as HTML).

Portability: ``build_site`` also embeds every data file a page uses inline,
as ``<script type="application/json" data-embed="<file>">``. The block is data (never
executed). A JSON file embeds its parsed value; a CSV file embeds its raw text as a JSON
string. The binding script prefers the embed and falls back to ``fetch`` only when it is
absent, so a site opens from ``file://``. ``check_site`` verifies each embed is valid
JSON and equals its ``site_data/`` file (``data.embed_*`` rules).
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
import re
from typing import Any

from .errors import SpecError

DATA_DIR = "site_data"
DATA_JS_PATH = "site_assets/rs-data.js"
DATA_FILE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*\.(json|csv)$")
SCRIPT_MARKER = "/* generated by reportsite - do not edit by hand */"
_HASH_LINE = re.compile(r"/\* reportsite-data-binding v1 sha256=([0-9a-f]{64}|@@) \*/")

_BODY = r"""/* generated by reportsite - do not edit by hand */
/* reportsite-data-binding v1 sha256=@@ */
(function () {
  var DIR = "site_data/";
  var cache = {};

  function parseCsv(text) {
    var rows = [], row = [], cell = "", q = false, i = 0, c;
    if (text.charCodeAt(0) === 0xFEFF) { i = 1; }
    for (; i < text.length; i++) {
      c = text[i];
      if (q) {
        if (c === '"') { if (text[i + 1] === '"') { cell += '"'; i++; } else { q = false; } }
        else { cell += c; }
      } else if (c === '"') { q = true; }
      else if (c === ",") { row.push(cell); cell = ""; }
      else if (c === "\n" || c === "\r") {
        if (c === "\r" && text[i + 1] === "\n") { i++; }
        row.push(cell); cell = ""; rows.push(row); row = [];
      } else { cell += c; }
    }
    if (cell !== "" || row.length) { row.push(cell); rows.push(row); }
    if (!rows.length) { return []; }
    var head = rows[0];
    return rows.slice(1).map(function (r) {
      var o = {};
      head.forEach(function (h, k) { o[h] = r[k] === undefined ? "" : r[k]; });
      return o;
    });
  }

  function embedded(name) {
    var nodes = document.querySelectorAll('script[type="application/json"][data-embed]');
    for (var i = 0; i < nodes.length; i++) {
      if (nodes[i].getAttribute("data-embed") === name) { return nodes[i]; }
    }
    return null;
  }

  function load(name) {
    if (!cache[name]) {
      var node = embedded(name);
      if (node) {
        cache[name] = new Promise(function (resolve) {
          var v = JSON.parse(node.textContent);
          resolve(/\.csv$/i.test(name) ? parseCsv(v) : v);
        });
        return cache[name];
      }
      cache[name] = fetch(DIR + encodeURIComponent(name)).then(function (r) {
        if (!r.ok) { throw new Error("HTTP " + r.status); }
        return r.text();
      }).then(function (t) {
        return /\.csv$/i.test(name) ? parseCsv(t) : JSON.parse(t);
      });
    }
    return cache[name];
  }

  function fail(el, name, err) {
    el.classList.add("rs-data-error");
    el.textContent = "data unavailable: " + name + " (" + err.message + ")";
  }

  function keysOf(rows) {
    var seen = [];
    rows.forEach(function (r) {
      Object.keys(r).forEach(function (k) { if (seen.indexOf(k) < 0) { seen.push(k); } });
    });
    return seen;
  }

  function fill(el, rows) {
    if (!Array.isArray(rows)) { throw new Error("table data must be a list of rows"); }
    var cols = (el.getAttribute("data-columns") || "").split(",")
      .map(function (s) { return s.trim(); }).filter(Boolean);
    if (!cols.length) { cols = keysOf(rows); }
    var table = el.tagName === "TABLE" ? el : document.createElement("table");
    table.textContent = "";
    var thead = table.createTHead().insertRow();
    cols.forEach(function (c) {
      var th = document.createElement("th"); th.scope = "col"; th.textContent = c; thead.appendChild(th);
    });
    var tbody = table.createTBody();
    rows.forEach(function (r) {
      var tr = tbody.insertRow();
      cols.forEach(function (c) {
        var v = r[c];
        tr.insertCell().textContent = (v === undefined || v === null) ? "" :
          (typeof v === "object" ? JSON.stringify(v) : String(v));
      });
    });
    if (table !== el) { el.textContent = ""; el.appendChild(table); }
  }

  function pick(data, field) {
    var cur = Array.isArray(data) ? data[0] : data;
    var parts = field.split(".");
    for (var i = 0; i < parts.length; i++) {
      if (cur === null || typeof cur !== "object" || !(parts[i] in cur)) {
        throw new Error("no field " + field);
      }
      cur = cur[parts[i]];
    }
    return (cur !== null && typeof cur === "object") ? JSON.stringify(cur) : String(cur);
  }

  document.querySelectorAll("[data-table]").forEach(function (el) {
    var name = el.getAttribute("data-table");
    load(name).then(function (d) { fill(el, d); }).catch(function (e) { fail(el, name, e); });
  });
  document.querySelectorAll("[data-value]").forEach(function (el) {
    var ref = el.getAttribute("data-value"), at = ref.indexOf("#");
    var name = at < 0 ? ref : ref.slice(0, at), field = at < 0 ? "" : ref.slice(at + 1);
    load(name).then(function (d) { el.textContent = pick(d, field); })
      .catch(function (e) { fail(el, name, e); });
  });
})();
"""


def _digest(text_with_placeholder: str) -> str:
    return hashlib.sha256(text_with_placeholder.encode("utf-8")).hexdigest()


DATA_JS = _BODY.replace("@@", _digest(_BODY), 1)


def script_is_pristine(text: str) -> bool:
    """True iff ``text`` is a generated binding script whose content is unmodified."""
    if SCRIPT_MARKER not in text:
        return False
    m = _HASH_LINE.search(text)
    if not m or m.group(1) == "@@":
        return False
    return _digest(_HASH_LINE.sub(
        "/* reportsite-data-binding v1 sha256=@@ */", text, count=1)) == m.group(1)


# --------------------------------------------------------------------- embeds
_REF_RE = re.compile(r"""data-(?:table|value)\s*=\s*["']([^"'#]+)""")


def referenced_files(html_text: str) -> list[str]:
    """Data file names a page's containers reference (first-seen order, unique)."""
    out: list[str] = []
    for m in _REF_RE.finditer(html_text):
        if m.group(1) not in out:
            out.append(m.group(1))
    return out


def embed_payload(name: str, rendered: str) -> str:
    """JSON text for the inline embed of a rendered data file (safe inside <script>)."""
    value: Any = json.loads(rendered) if name.lower().endswith(".json") else rendered
    text = json.dumps(value, ensure_ascii=False)
    return (text.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
            .replace("\u2028", "\\u2028").replace("\u2029", "\\u2029"))


def embed_block(name: str, rendered: str) -> str:
    return (f'<script type="application/json" data-embed="{name}">'
            f"{embed_payload(name, rendered)}</script>\n")


# ------------------------------------------------------------------ data files
def csv_columns(rows: list[dict[str, Any]]) -> list[str]:
    cols: list[str] = []
    for r in rows:
        for k in r:
            if k not in cols:
                cols.append(k)
    return cols


def render_data_file(name: str, content: Any) -> str:
    """Serialise one ``site_data`` file; raise SpecError on a bad name/content."""
    if not isinstance(name, str) or not DATA_FILE_RE.match(name):
        raise SpecError(f"data file name {name!r} must match {DATA_FILE_RE.pattern}")
    if name.lower().endswith(".json"):
        try:
            return json.dumps(content, ensure_ascii=False, indent=2) + "\n"
        except (TypeError, ValueError) as exc:
            raise SpecError(f"data file {name!r} is not JSON-serialisable: {exc}") from exc
    if not isinstance(content, list) or not all(isinstance(r, dict) for r in content):
        raise SpecError(f"CSV data file {name!r} must be a list of row objects")
    cols = csv_columns(content)
    if not cols:
        raise SpecError(f"CSV data file {name!r} needs at least one column")
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=cols, lineterminator="\n")
    w.writeheader()
    for r in content:
        w.writerow({k: ("" if v is None else v) for k, v in r.items()})
    return buf.getvalue()


def parse_data_file(name: str, text: str) -> Any:
    """Parse JSON (any value) or CSV (list of dict rows). Raise ValueError if malformed."""
    if name.lower().endswith(".json"):
        return json.loads(text)
    if text.startswith("﻿"):
        text = text[1:]
    reader = csv.reader(io.StringIO(text), strict=True)
    try:
        table = list(reader)
    except csv.Error as exc:
        raise ValueError(str(exc)) from exc
    if not table or not any(c.strip() for c in table[0]):
        raise ValueError("CSV has no header row")
    head = table[0]
    if len(set(head)) != len(head):
        raise ValueError("CSV header has duplicate columns")
    rows = []
    for i, r in enumerate(table[1:], start=2):
        if len(r) != len(head):
            raise ValueError(f"CSV row {i} has {len(r)} cells, header has {len(head)}")
        rows.append(dict(zip(head, r)))
    return rows


def lookup_field(data: Any, field: str) -> bool:
    """Does the dotted ``field`` exist (JSON object, or first CSV row)?"""
    cur = data[0] if isinstance(data, list) and data else data
    if not isinstance(cur, dict):
        return False
    for part in field.split("."):
        if not isinstance(cur, dict) or part not in cur:
            return False
        cur = cur[part]
    return True
